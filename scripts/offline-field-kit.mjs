import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const FIELD_KIT_ROUTES = [
  "/radio/",
  "/radio/glossary/",
  "/radio/shack/",
  "/radio/equipment/",
  "/radio/cw-practice/",
  "/radio/cw-qso/",
  "/radio/beacons/",
  "/radio/field-log/",
  "/radio/rbn-skimmers/",
];

export const CACHE_PREFIX = "rwjblue-field-kit";
export const MAX_RUNTIME_ENTRIES = 24;
const STATIC_DEPENDENCIES = ["/manifest.webmanifest", "/favicon.svg"];
const GENERATOR_SOURCE = fileURLToPath(import.meta.url);

const outputPathFor = (distDirectory, pathname) => {
  const relative = pathname.replace(/^\/+/, "");
  return pathname.endsWith("/")
    ? join(distDirectory, relative, "index.html")
    : join(distDirectory, relative);
};

const isFieldKitDependency = (pathname) =>
  pathname.startsWith("/_astro/") ||
  pathname.startsWith("/assets/") ||
  /\.(?:css|js|mjs|svg|png|webp|woff2?|webmanifest)$/.test(pathname);

export function collectFieldKitDependencies(distDirectory) {
  const paths = new Set([...FIELD_KIT_ROUTES, ...STATIC_DEPENDENCIES]);

  for (const route of FIELD_KIT_ROUTES) {
    const html = readFileSync(outputPathFor(distDirectory, route), "utf8");
    for (const tag of html.matchAll(/<(?:script|link|img)\b[^>]*>/gi)) {
      for (const attribute of tag[0].matchAll(/\b(?:src|href)="([^"]+)"/gi)) {
        const value = attribute[1];
        if (!value.startsWith("/")) continue;
        const pathname = new URL(value, "https://rwjblue.com").pathname;
        if (isFieldKitDependency(pathname)) paths.add(pathname);
      }
    }
  }

  return [...paths].sort();
}

export function fieldKitVersion(distDirectory, paths) {
  const hash = createHash("sha256");
  hash.update(readFileSync(GENERATOR_SOURCE));
  for (const pathname of paths) {
    hash.update(`${pathname}\0`);
    hash.update(readFileSync(outputPathFor(distDirectory, pathname)));
  }
  return hash.digest("hex").slice(0, 12);
}

export function buildOfflineFieldKit(distDirectory) {
  const precache = collectFieldKitDependencies(distDirectory);
  const version = fieldKitVersion(distDirectory, precache);
  return {
    precache,
    version,
    source: renderServiceWorker({ precache, version }),
  };
}

export function renderServiceWorker({ precache, version }) {
  const coreCache = `${CACHE_PREFIX}-core-${version}`;
  const runtimeCache = `${CACHE_PREFIX}-runtime-${version}`;

  return `/* Generated by scripts/build-service-worker.mjs. */
const VERSION = ${JSON.stringify(version)};
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CORE_CACHE = ${JSON.stringify(coreCache)};
const RUNTIME_CACHE = ${JSON.stringify(runtimeCache)};
const MAX_RUNTIME_ENTRIES = ${MAX_RUNTIME_ENTRIES};
const FIELD_KIT_ROUTES = ${JSON.stringify(FIELD_KIT_ROUTES, null, 2)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CORE_CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter(
              (key) =>
                key.startsWith(\`\${CACHE_PREFIX}-\`) &&
                key !== CORE_CACHE &&
                key !== RUNTIME_CACHE,
            )
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate" && isEligibleRadioRoute(url.pathname)) {
    event.respondWith(networkFirstRadioPage(request, url));
    return;
  }

  if (url.pathname.startsWith("/_astro/") || url.pathname.startsWith("/assets/")) {
    event.respondWith(cacheFirstAsset(request));
  }
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "FIELD_KIT_VERSION") {
    event.source?.postMessage({ type: "FIELD_KIT_VERSION", version: VERSION });
  }
});

function isEligibleRadioRoute(pathname) {
  return (
    pathname.startsWith("/radio/") &&
    !pathname.includes("/share-image") &&
    !/\\.(?:png|xml|json)$/.test(pathname)
  );
}

function navigationKey(url) {
  return new Request(\`\${url.origin}\${url.pathname}\`);
}

async function networkFirstRadioPage(request, url) {
  const key = navigationKey(url);
  try {
    const response = await fetch(request);
    if (response.status >= 500) {
      return (await caches.match(key)) || response;
    }
    if (
      response.ok &&
      response.headers.get("content-type")?.includes("text/html")
    ) {
      const cacheName = FIELD_KIT_ROUTES.includes(url.pathname)
        ? CORE_CACHE
        : RUNTIME_CACHE;
      const cache = await caches.open(cacheName);
      await cache.put(key, response.clone());
      if (cacheName === RUNTIME_CACHE) await trimRuntimeCache();
    }
    return response;
  } catch {
    return (
      (await caches.match(key)) ||
      (await caches.match("/radio/")) ||
      Response.error()
    );
  }
}

async function cacheFirstAsset(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(RUNTIME_CACHE);
    await cache.put(request, response.clone());
    await trimRuntimeCache();
  }
  return response;
}

async function trimRuntimeCache() {
  const cache = await caches.open(RUNTIME_CACHE);
  const keys = await cache.keys();
  await Promise.all(
    keys.slice(0, Math.max(0, keys.length - MAX_RUNTIME_ENTRIES)).map((key) =>
      cache.delete(key),
    ),
  );
}
`;
}
